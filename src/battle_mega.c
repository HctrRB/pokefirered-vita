const u8 *Mega_AbilityName(u8 ability)
{
    if (ability < ABILITIES_COUNT)
        return gAbilityNames[ability];
    if (ability < MEGA_ABILITIES_END)
        return sAbilityNames[ability - ABILITIES_COUNT];
    return gAbilityNames[ABILITY_NONE];
}

