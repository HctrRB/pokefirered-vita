#define NO_ATE_TYPE 0xFF

/* Aerilate, Pixilate, Refrigerate, Dragonize: the type a Normal-type move
 * takes, or NO_ATE_TYPE. FireRed has no Fairy type: Pixilate gives the
 * Pokémon's own first type (Psychic for Gardevoir, Dragon for Altaria). */
static u8 AteType(u8 battlerAtk, u16 move)
{
    u8 type;

    switch (gBattleMons[battlerAtk].ability)
    {
    case ABILITY_AERILATE:    type = TYPE_FLYING; break;
    case ABILITY_REFRIGERATE: type = TYPE_ICE; break;
    case ABILITY_DRAGONIZE:   type = TYPE_DRAGON; break;
    case ABILITY_PIXILATE:    type = gBattleMons[battlerAtk].type1; break;
    default:                  return NO_ATE_TYPE;
    }
    if (gBattleMoves[move].type != TYPE_NORMAL || gBattleMoves[move].power == 0 || move == MOVE_STRUGGLE
     || gBattleMoves[move].effect == EFFECT_HIDDEN_POWER || gBattleMoves[move].effect == EFFECT_WEATHER_BALL)
        return NO_ATE_TYPE;
    return type;
}

/* In FireRed a move is physical or special by its type. A move that one of
 * these abilities turned stays what it was: physical, as a Normal move. */
u8 Mega_CategoryType(u8 battlerAtk, u16 move, u8 type)
{
    return AteType(battlerAtk, move) != NO_ATE_TYPE ? TYPE_NORMAL : type;
}

/* Sheer Force: a move with a chance of a further effect, which it loses for
 * more power. Not the ones whose effect is on the user or is the move. */
static bool8 SheerForceMove(u16 move)
{
    u8 effect = gBattleMoves[move].effect;

    return gBattleMoves[move].power != 0 && gBattleMoves[move].secondaryEffectChance != 0
        && effect != EFFECT_OVERHEAT && effect != EFFECT_SUPERPOWER && effect != EFFECT_RAPID_SPIN
        && effect != EFFECT_KNOCK_OFF && effect != EFFECT_THIEF;
}

bool8 Mega_SheerForce(u8 battlerAtk, u16 move)
{
    if (gBattleMons[battlerAtk].ability != ABILITY_SHEER_FORCE || !SheerForceMove(move))
        return FALSE;
#ifdef CTR_DEBUG_MEGA
    MEGA_LOG("mega debug: sheer force drops the effect of move %u", move);
#endif
    return TRUE;
}

/* A move's power (CalculateBaseDamage): Tough Claws, Mega Launcher, the -ate
 * abilities, Sand Force, Technician, Strong Jaw, Sheer Force. */
u16 Mega_ModifyPower(u8 battlerAtk, u16 move, u16 power)
{
    u8 type = gBattleMoves[move].type;
#ifdef CTR_DEBUG_MEGA
    u16 before = power;
#endif

    switch (gBattleMons[battlerAtk].ability)
    {
    case ABILITY_TOUGH_CLAWS:
        if (gBattleMoves[move].flags & FLAG_MAKES_CONTACT)
            power = power * 130 / 100;
        break;
    case ABILITY_MEGA_LAUNCHER:
        if (move == MOVE_WATER_PULSE)
            power = power * 150 / 100;
        break;
    case ABILITY_AERILATE:
    case ABILITY_PIXILATE:
    case ABILITY_REFRIGERATE:
        if (AteType(battlerAtk, move) != NO_ATE_TYPE)
            power = power * 130 / 100;
        break;
    case ABILITY_DRAGONIZE:
        if (AteType(battlerAtk, move) != NO_ATE_TYPE)
            power = power * 120 / 100;
        break;
    case ABILITY_SAND_FORCE:
        if (WEATHER_HAS_EFFECT2 && (gBattleWeather & B_WEATHER_SANDSTORM)
         && (type == TYPE_ROCK || type == TYPE_GROUND || type == TYPE_STEEL))
            power = power * 130 / 100;
        break;
    case ABILITY_TECHNICIAN:
        if (power <= 60)
            power = power * 150 / 100;
        break;
    case ABILITY_STRONG_JAW:
        if (move == MOVE_BITE || move == MOVE_CRUNCH || move == MOVE_HYPER_FANG)
            power = power * 150 / 100;
        break;
    case ABILITY_SHEER_FORCE:
        if (SheerForceMove(move))
            power = power * 130 / 100;
        break;
    }
#ifdef CTR_DEBUG_MEGA
    if (power != before)
        MEGA_LOG("mega debug: ability %u, move %u power %u -> %u", gBattleMons[battlerAtk].ability, move, before, power);
#endif
    return power;
}

/* Solar Power: Sp. Atk half again in sunshine. */
u16 Mega_ModifySpAttack(u8 battlerAtk, u16 spAttack)
{
    if (gBattleMons[battlerAtk].ability == ABILITY_SOLAR_POWER && WEATHER_HAS_EFFECT2 && (gBattleWeather & B_WEATHER_SUN))
        spAttack = spAttack * 150 / 100;
    return spAttack;
}

/* Filter: a super-effective blow does three quarters of its damage. */
s32 Mega_AfterTypeCalc(u8 battlerDef, s32 damage, u8 flags)
{
    if (gBattleMons[battlerDef].ability == ABILITY_FILTER && (flags & MOVE_RESULT_SUPER_EFFECTIVE) && damage > 1)
    {
#ifdef CTR_DEBUG_MEGA
        MEGA_LOG("mega debug: filter %d -> %d", (int)damage, (int)(damage * 3 / 4));
#endif
        damage = damage * 3 / 4;
    }
    return damage;
}

/* Delta Stream: while it is on the field, nothing is super effective on a
 * Flying type for being Flying. */
u8 Mega_TypeMultiplier(u8 defType, u8 multiplier)
{
    u8 i;

    if (defType != TYPE_FLYING || multiplier != TYPE_MUL_SUPER_EFFECTIVE)
        return multiplier;
    for (i = 0; i < gBattlersCount; i++)
        if (gBattleMons[i].ability == ABILITY_DELTA_STREAM && gBattleMons[i].hp != 0)
        {
#ifdef CTR_DEBUG_MEGA
            MEGA_LOG("mega debug: delta stream, Flying not weak");
#endif
            return TYPE_MUL_NORMAL;
        }
    return multiplier;
}

/* Prankster: status moves go first, as a move of priority one more. */
s8 Mega_MovePriority(u8 battler, u16 move)
{
    s8 priority;

    if (move == MOVE_NONE || move >= MOVES_COUNT)
        return 0;
    priority = gBattleMoves[move].priority;

    if (gBattleMons[battler].ability == ABILITY_PRANKSTER && gBattleMoves[move].power == 0)
    {
        priority++;
#ifdef CTR_DEBUG_MEGA
        MEGA_LOG("mega debug: prankster, move %u priority %d", move, priority);
#endif
    }
    return priority;
}

/* Magic Bounce: status moves that Magic Coat would send back are sent back,
 * every time; a move bounced once is not bounced again. */
bool8 Mega_MagicBounce(u8 battlerDef)
{
    if (gBattleMons[battlerDef].ability != ABILITY_MAGIC_BOUNCE || sMega.bounced)
        return FALSE;
    sMega.bounced = TRUE;
    MEGA_LOG("mega: magic bounce, battler %u", battlerDef);
    return TRUE;
}

/* Stalwart: Follow Me and Lightning Rod don't draw this Pokémon's moves. */
bool8 Mega_Stalwart(u8 battlerAtk)
{
    return gBattleMons[battlerAtk].ability == ABILITY_STALWART;
}

/* Multiscale: a blow taken at full HP does half damage.
 * Parental Bond: the parent and its child both hit. The second hit's quarter
 * comes with the first, as one blow (single-target moves that hit once). */
s32 Mega_ModifyDamage(u8 battlerAtk, u8 battlerDef, u16 move, s32 damage)
{
    u8 effect = gBattleMoves[move].effect;

    if (gBattleMons[battlerDef].ability == ABILITY_MULTISCALE && gBattleMons[battlerDef].hp == gBattleMons[battlerDef].maxHP)
    {
#ifdef CTR_DEBUG_MEGA
        MEGA_LOG("mega debug: multiscale halves %d", (int)damage);
#endif
        damage /= 2;
    }

    if (gBattleMons[battlerAtk].ability != ABILITY_PARENTAL_BOND || gBattleMoves[move].power == 0)
        return damage;
    if (gBattleMoves[move].target & (MOVE_TARGET_BOTH | MOVE_TARGET_FOES_AND_ALLY))
        return damage;
    if (effect == EFFECT_MULTI_HIT || effect == EFFECT_DOUBLE_HIT || effect == EFFECT_TRIPLE_KICK
     || effect == EFFECT_TWINEEDLE || effect == EFFECT_BEAT_UP || effect == EFFECT_EXPLOSION)
        return damage;
    return damage + damage / 4;
}

