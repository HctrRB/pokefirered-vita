const u8 *Mega_BattleString(u16 stringId)
{
    static u8 buf[96];
    s8 f;

    if (stringId == STRINGID_MEGA_REACTING)
        return GetBattlerSide(gBattlerAttacker) == B_SIDE_PLAYER ? sText_ReactingPlayer : sText_ReactingFoe;
    if (stringId == STRINGID_MEGA_SOLAR_POWER)
        return sText_SolarPower;
    if (stringId == STRINGID_MEGA_DELTA_STREAM)
        return sText_DeltaStream;
    if (stringId == STRINGID_MEGA_MAGIC_BOUNCE)
        return sText_MagicBounce;
    f = FormOf(gBattlerAttacker);
    if (f < 0)
        f = sMega.evolving;
    StringAppend(StringAppend(StringCopy(buf, sText_EvolvedInto), sForms[f].name), sText_Exclamation);
    return buf;
}

