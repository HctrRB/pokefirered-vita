/* A form taller than its base form sits lower in its 64x64 box (so its top
 * is not cut) and has a smaller y_offset; the battle places the sprite with
 * it, which keeps the feet on the base form's row. Base: the species' own. */
u8 Mega_PicYOffset(u8 battler, u16 species, u8 base)
{
    s8 f;

    if (!gMain.inBattle || battler >= MAX_BATTLERS_COUNT || gBattleSpritesDataPtr == NULL)
        return base;
    f = FormOf(battler);
    if (f < 0 || species != sForms[f].species
     || gBattleSpritesDataPtr->battlerData[battler].transformSpecies != SPECIES_NONE)
        return base;
    return gMegaYOffsets[f][GetBattlerSide(battler) == B_SIDE_PLAYER];
}

static void LoadFormPicture(u8 battler, s8 f, bool8 toVram)
{
    bool8 back = GetBattlerSide(battler) == B_SIDE_PLAYER;
    u8 position = GetBattlerPosition(battler);

    CpuCopy32(gMegaPics[f][back], gMonSpritesGfxPtr->sprites[position], MON_PIC_SIZE);
    if (toVram)
    {
        struct Sprite *sprite = &gSprites[gBattlerSpriteIds[battler]];
        u16 species = sForms[f].species;
        u8 base = back ? gMonBackPicCoords[species].y_offset : gMonFrontPicCoords[species].y_offset;

        CpuCopy32(gMegaPics[f][back], (u8 *)OBJ_VRAM0 + sprite->oam.tileNum * TILE_SIZE_4BPP, MON_PIC_SIZE);
        /* on screen: lift it by the rows it moved down in its box */
        sprite->y -= base - gMegaYOffsets[f][back];
    }
}

