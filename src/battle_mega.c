/* Before the turn's first action: the next Pokémon (in turn order) that
 * Mega Evolves runs BattleScript_MegaEvolution. The player chooses with the
 * MEGA key; a trainer's Pokémon always does when it can. */
bool8 Mega_TryStartTurn(void)
{
    int i;

    for (i = 0; i < gBattlersCount; i++)
    {
        u8 battler = gBattlerByTurnOrder[i];
        s8 f;

        if (gChosenActionByBattler[battler] != B_ACTION_USE_MOVE)
            continue;
        if (GetBattlerSide(battler) == B_SIDE_PLAYER && !sMega.toggled[battler])
            continue;
        f = FormIfCanEvolve(battler);
        if (f < 0)
            continue;
        sMega.toggled[battler] = FALSE;
        sMega.evolving = f;
        sMega.step = 0;
        gBattlerAttacker = gActiveBattler = battler;
        gLastUsedItem = gBattleMons[battler].item;
        MEGA_LOG("mega: battler %u (species %u) takes form %d", battler, gBattleMons[battler].species, f);
        BattleScriptExecute(BattleScript_MegaEvolution);
        return TRUE;
    }
    Mega_TurnDone();
    return FALSE;
}

void Mega_TurnDone(void)
{
    memset(sMega.toggled, 0, sizeof(sMega.toggled));
#ifdef CTR_DEBUG_MEGA
    sMega.toggled[0] = TRUE;
#endif
}

/* megaevolve battler, phase: phase 0 is the change itself (a flash to white,
 * the new picture, the flash back, its cry); phase 1 its ability on entry. */
void Mega_Cmd(void)
{
    u8 battler, side;

    if (gBattleControllerExecFlags)
        return;
    battler = GetBattlerForBattleScript(gBattlescriptCurrInstr[1]);
    side = GetBattlerSide(battler);
    if (gBattlescriptCurrInstr[2] == 1)
    {
        gBattlescriptCurrInstr += 3;
        if (gBattleMons[battler].ability == ABILITY_DELTA_STREAM)
        {
            /* the strong winds end the weather there was */
            gBattleWeather = 0;
            gBattleScripting.battler = battler;
            BattleScriptPushCursor();
            gBattlescriptCurrInstr = BattleScript_DeltaStreamActivates;
            return;
        }
        if (!AbilityBattleEffects(ABILITYEFFECT_ON_SWITCHIN, battler, 0, 0, 0)
         && !AbilityBattleEffects(ABILITYEFFECT_INTIMIDATE2, battler, 0, 0, 0))
            AbilityBattleEffects(ABILITYEFFECT_TRACE, 0, 0, 0, 0);
        return;
    }
    switch (sMega.step)
    {
    case 0:
        sMega.form[side][gBattlerPartyIndexes[battler] % PARTY_SIZE] = sMega.evolving + 1;
        sMega.used[side] = TRUE;
        Mega_RefreshStats(battler);
        PlaySE(SE_M_MEGA_KICK);
        MegaFx_Begin(battler);
        sMega.step++;
        break;
    default:
        if (!MegaFx_Update(sMega.evolving))
            break;
        sMega.step = 0;
        gBattlescriptCurrInstr += 3;
        break;
    }
}

